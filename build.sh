#!/usr/bin/env bash
# Bundles lib/*.sh into a single dist/server file — the artifact that
# actually gets installed to PATH, so `server` stays a one-file copy/chmod
# install for users even though the source is split into modules.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$SCRIPT_DIR/dist/server"

mkdir -p "$SCRIPT_DIR/dist"

{
    echo "#!/usr/bin/env bash"
    echo "# Generated by build.sh — do not edit directly, edit lib/ and rerun ./build.sh"
    echo "set -u"
    echo ""
    echo "# Restores terminal echo on any exit path (normal, error, or Ctrl-C) — a"
    echo "# \`read -rsp\` password prompt interrupted mid-read can otherwise leave the"
    echo "# terminal without local echo, which is confusing since it isn't obvious"
    echo "# what happened. This is a cheap no-op when echo was never disabled."
    echo "trap 'stty echo 2>/dev/null' EXIT"
    echo ""
    echo 'if [[ -z "${HOME:-}" ]]; then'
    echo '    echo "❌ \$HOME is not set — serverctx needs it to find ~/.ssh. Set it and try again." >&2'
    echo "    exit 1"
    echo "fi"
    echo ""
    echo '# GPG_RECIPIENT is resolved by gpg_recipient() in crypto.sh below'
    echo '# (env override > ~/.ssh/.gpg_recipient from `server init` > $USER).'
    echo 'SSH_CONFIG_FILE="${SSH_CONFIG_FILE:-$HOME/.ssh/config}"'
    echo 'CRED_FILE="${CRED_FILE:-$HOME/.ssh/server_credentials}"'
    echo 'RECENT_FILE="${RECENT_FILE:-$HOME/.ssh/.serverctx_recent}"'
    echo 'backup_dir="./serverctx_backup"'
    echo ""

    # ui.sh must follow os.sh — it calls supports_color at source time.
    for f in "$SCRIPT_DIR"/lib/os.sh "$SCRIPT_DIR"/lib/ui.sh "$SCRIPT_DIR"/lib/crypto.sh "$SCRIPT_DIR"/lib/sshconfig.sh "$SCRIPT_DIR"/lib/commands/*.sh; do
        echo "# --- $(basename "$f") ---"
        cat "$f"
        echo ""
    done

    cat <<'EOF'
case "${1:-}" in
    init|initialize|in|-i)  cmd_init ;;
    add|ad)                 cmd_add ;;
    rm|remove|del|delete)   cmd_remove ;;
    edit|-e)                cmd_edit ;;
    list|ls)                shift; cmd_list "$@" ;;
    ssh|"")                 cmd_ssh ;;
    pswd|password)          cmd_pswd ;;
    --help|help|-h)         cmd_help ;;
    backup|export)          cmd_backup ;;
    restore|import)         cmd_restore ;;
    editgroup|-eg)          cmd_editgroup ;;
    remember|-r)            cmd_remember ;;
    download|-d)            cmd_download ;;
    upload|-u)              cmd_upload ;;
    *)
        echo "❌ Unknown command: $1"
        cmd_help
        exit 1
        ;;
esac
EOF
} > "$OUT"

chmod +x "$OUT"
echo "✅ Built $OUT"
